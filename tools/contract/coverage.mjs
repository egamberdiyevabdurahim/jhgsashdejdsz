#!/usr/bin/env node
// tools/contract/coverage.mjs — what the corpus covers: every /api/v1 route x method (src/app/api/v1/**/route.ts) against every recording
// in contract/recordings/. Writes contract/COVERAGE.md (and prints the totals): per route x method, the exchanges recorded, the statuses
// seen, whether a 2xx (a happy path) is among them, and under which profiles.
//
//   node tools/contract/coverage.mjs [--replays]   --replays adds the last replay result per recording (contract/.run/replay-*.json)
import { readdirSync, writeFileSync, existsSync, readFileSync } from 'node:fs'
import path from 'node:path'
import { ROOT, REC, RUN } from './env.mjs'
import { routes, routeOf, readRecording } from './lib.mjs'

const R = routes()
const cov = new Map()
for (const r of R) for (const m of r.methods.filter(x => x !== 'HEAD')) cov.set(`${m} ${r.route}`, { route: r.route, method: m, n: 0, statuses: new Set(), profiles: new Set(), sessions: new Set() })
const files = readdirSync(REC).filter(f => f.endsWith('.jsonl')).sort()
let total = 0, unknown = 0
const perFile = []
for (const f of files) {
  const { meta, entries } = readRecording(path.join(REC, f))
  const http = entries.filter(e => e.type === 'http')
  perFile.push({ f, profile: meta?.profile, n: http.length, pages: entries.filter(e => e.type === 'page').length, sql: entries.filter(e => e.type === 'sql').length, walk: meta?.walk })
  for (const e of http) {
    total++
    const route = routeOf(R, e.path), c = route && cov.get(`${e.method} ${route}`)
    if (!c) { unknown++; continue }
    c.n++; c.statuses.add(e.status); c.profiles.add(meta?.profile); c.sessions.add(f.replace(/\.jsonl$/, ''))
  }
}
const rows = [...cov.values()].sort((a, b) => a.route.localeCompare(b.route) || a.method.localeCompare(b.method))
const covered = rows.filter(r => r.n), happy = rows.filter(r => [...r.statuses].some(s => s >= 200 && s < 300))
let replays = ''
if (process.argv.includes('--replays')) {
  // the last replay of each recording that is newer than the recording itself (contract/.run/replay-<name>.json, gitignored)
  const rows = []
  for (const f of files) {
    const name = f.replace(/\.jsonl$/, ''), rp = path.join(RUN, `replay-${name}.json`)
    if (!existsSync(rp)) { rows.push(`| ${name} | not replayed | | | | | |`); continue }
    const r = JSON.parse(readFileSync(rp, 'utf8')), { meta } = readRecording(path.join(REC, f))
    if (Date.parse(r.replayedAt) < Date.parse(meta.recordedAt)) { rows.push(`| ${name} | replay older than the recording | | | | | |`); continue }
    rows.push(`| ${name} | ${r.base} | ${r.exchanges} | ${r.pass} | ${r.fail} | ${r.pages ? `${r.pagesSame}/${r.pages}` : '-'} | ${r.sqlRun} |`)
  }
  replays = '\n## Replays against the TypeScript backend (fresh seed copy, fresh server)\n\n| recording | target | /api/v1 exchanges | same | differ | pages same | sql run |\n|---|---|---|---|---|---|---|\n' + rows.join('\n') + '\n'
}
const md = `# Contract corpus coverage

Generated by \`node tools/contract/coverage.mjs\` from contract/recordings/*.jsonl against src/app/api/v1/**/route.ts.

- Route x method pairs (HEAD left out): **${rows.length}**; with at least one recorded exchange: **${covered.length}**; with a 2xx among them: **${happy.length}**.
- Exchanges recorded: ${total} in ${files.length} recordings${unknown ? `; ${unknown} on paths no route file matches` : ''}.

## Recordings

| recording | profile | /api/v1 exchanges | pages | sql writes | walk exit |
|---|---|---|---|---|---|
${perFile.map(p => `| ${p.f} | ${p.profile} | ${p.n} | ${p.pages} | ${p.sql} | ${p.walk ? p.walk.exit : '-'} |`).join('\n')}
${replays}
## Per route

| method | route | exchanges | statuses | 2xx | recordings |
|---|---|---|---|---|---|
${rows.map(r => `| ${r.method} | ${r.route} | ${r.n} | ${[...r.statuses].sort().join(' ')} | ${[...r.statuses].some(s => s >= 200 && s < 300) ? 'yes' : r.n ? 'no' : '-'} | ${[...r.sessions].sort().join(' ')} |`).join('\n')}
`
writeFileSync(path.join(ROOT, 'contract/COVERAGE.md'), md)
console.log(`routes x methods ${rows.length}; covered ${covered.length}; with 2xx ${happy.length}; exchanges ${total} in ${files.length} recordings`)
if (existsSync(RUN)) writeFileSync(path.join(RUN, 'coverage.json'), JSON.stringify(rows.map(r => ({ ...r, statuses: [...r.statuses], profiles: [...r.profiles], sessions: [...r.sessions] })), null, 1))
