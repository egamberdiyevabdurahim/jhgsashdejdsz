  var ACT_MORE = ['category', 'role', 'founded_or_joined', 'weeks_per_year', 'years', 'evidence_url'], ACT_KEYS = ['name', 'hours_per_week'].concat(ACT_MORE)
  function actFilled(v) { return v != null && String(v).trim() !== '' }
  /** The answer the rows make: every row with something in it, its filled fields only (and whatever else the stored row carried);
   *  undefined while a row has details and no name (Continue stays off). */
  function activitiesRows(rows) {
    var out = [], ok = true
    rows.forEach(function (r) {
      var any = ACT_KEYS.some(function (k) { return actFilled(r[k]) })
      if (!any) return
      if (!actFilled(r.name)) { ok = false; return }
      var o = {}, k
      for (k in r) if (Object.prototype.hasOwnProperty.call(r, k) && k !== '_open' && (ACT_KEYS.indexOf(k) < 0 || actFilled(r[k]))) o[k] = typeof r[k] === 'string' ? r[k].trim() : r[k]
      out.push(o)
    })
    return ok ? out : undefined
  }
